"""Контракт джерела вакансій.

Вимога власника з першого дня: канали додаються без переробки ядра. Djinni і
DOU — лише перші два; далі Telegram-канали, RSS, окремі сайти компаній.

Тому форма одна для всіх: джерело вміє лише ПРИНЕСТИ сире, а вирішувати, чи
вакансія придатна, — не його справа. Змішати ці дві ролі означало б
переписувати скринер щоразу, коли з'являється новий канал.

Два свідомі рішення у `RawVacancy`:

1. **`payload` зберігається цілком.** Розмітка майданчика змінюється без
   попередження, і поле, яке сьогодні здається зайвим, завтра виявляється
   єдиним способом відрізнити вакансію від її ж перепублікації. Сире тіло
   лежить окремо (`vacancy_raw`), щоб переразбір не вимагав нового походу в
   мережу — той самий принцип, що й у прогнозній системі з `raw_document`.

2. **Нормалізація НЕ тут.** Джерело віддає рядки як є («1 рік досвіду»,
   «Англійська - A2»), а розбір їх у числа робить окремий шар. Інакше кожен
   новий канал тягнув би за собою власну копію тлумачень, і вони неминуче
   розійшлися б.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Protocol, Sequence, runtime_checkable


@dataclass(frozen=True)
class RawVacancy:
    """Вакансія, як її віддав канал. Нічого не тлумачено."""

    source_key: str
    external_id: str
    url: str
    title: str
    company: str

    # Текст оголошення. Саме за ним працює скринер, тому це єдине поле, яке
    # зобов'язане бути змістовним у КОЖНОГО каналу, хай яка в нього розмітка.
    raw_text: str = ""

    posted_at: datetime | None = None

    # Усе інше, що канал зумів повідомити: формат, досвід, англійська,
    # кількість відгуків, теги. Ключі — спільні там, де зміст справді
    # спільний; решта лишається як є під власною назвою каналу.
    payload: dict = field(default_factory=dict)

    @property
    def dedup_key(self) -> tuple[str, str]:
        """Ключ першого рівня: канал плюс його власний ідентифікатор.

        Другий рівень (компанія + посада) живе у шарі дедуплікації, бо він
        потрібен лише тоді, коли та сама вакансія приходить РІЗНИМИ каналами,
        і джерело про це знати не може."""
        return (self.source_key, self.external_id)


